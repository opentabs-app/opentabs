// Copy the OpenSync browser client into this repository.
//
// The extension used to import it across a sibling checkout
// (../../../../../opensync/packages/client/src), which meant nobody without
// the engine beside this repo could build it — CI included: the v0.1.0-rc.4
// release failed on exactly that import. opensync-obsidian solved the same
// problem the same way, and this follows its script.
//
//   node scripts/vendor-opensync.mjs           refresh the copy
//   node scripts/vendor-opensync.mjs --check   fail if it has drifted
//
// The copy is generated, never edited. `--check` runs in `npm test` wherever
// the engine is present, so a stale copy is caught rather than shipped.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const EXT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(EXT, "../../../opensync/packages/client/src");
const VENDOR = join(EXT, "vendor/opensync-client");
const STAMP = join(VENDOR, "VENDORED.json");

// Everything `index.ts` re-exports, plus the wasm-bindgen glue and the loose
// binary. `ui/` is the web apps' shared components and nothing here reaches
// it. The binary is copied rather than the engine's `wasm/inline.ts`: an
// extension loads the wasm off its own disk (see src/background/opensync-wasm.ts),
// so the base64 copy would be a megabyte of duplicate in every bundle.
const FILES = [
  "index.ts",
  "hosted.ts",
  "relay.ts",
  "session.ts",
  "pairing.ts",
  "qr.ts",
  "scan.ts",
  "vault.ts",
  "wasm/opensync_wasm.js",
  "wasm/opensync_wasm.d.ts",
  "wasm/opensync_wasm_bg.wasm",
];

// Stands in for the engine's `wasm/inline.ts`, which `ready()` imports
// dynamically when it is given no source. It is never read here, because
// `boot()` always passes the binary's URL; and if that ever stops being true,
// `ready()` refuses the empty string with its own "call ready(url) first"
// error on the first sync rather than doing something subtle.
const INLINE_STUB = `// Generated by scripts/vendor-opensync.mjs. Do not edit.
//
// The engine's own copy of this file is its wasm as base64. The extension
// loads the binary beside it instead (see src/background/opensync-wasm.ts), so
// this is empty on purpose: ready(url) never reads it, and ready() without a
// URL refuses it loudly.
export const WASM_BASE64 = "";
`;

/**
 * What a vendored file should contain, given the engine's copy of it.
 *
 * The engine writes its client for `strict`. This project also turns on
 * `noUncheckedIndexedAccess`, and tsc follows the imports into this copy and
 * holds it to that too: six errors in code nobody here may edit. So each `.ts`
 * file (not the `.d.ts`, not the binary) gets a `@ts-nocheck` line on top.
 * Its types still flow out, so every call OpenTabs makes into the client is
 * checked as strictly as the rest of the extension; only the client's own
 * bodies are left to the engine, where they are checked under `strict`.
 *
 * The check applies this too, so a marked copy still matches its source.
 */
const NOCHECK = "// @ts-nocheck -- vendored; see scripts/vendor-opensync.mjs\n";
function vendored(path) {
  const bytes = readFileSync(path);
  if (!/\.ts$/.test(path) || /\.d\.ts$/.test(path)) return bytes;
  return Buffer.concat([Buffer.from(NOCHECK), bytes]);
}

const sha = (bytes) => createHash("sha256").update(bytes).digest("hex").slice(0, 16);
const check = process.argv.includes("--check");

if (!existsSync(SOURCE)) {
  // Not an error: CI and most clones never have the engine, and do not need
  // it. That is the point of vendoring.
  console.log(`no engine at ${relative(EXT, SOURCE)} — nothing to ${check ? "check" : "refresh"}`);
  process.exit(0);
}

if (check) {
  const drifted = [];
  for (const f of FILES) {
    const mine = join(VENDOR, f);
    if (!existsSync(mine)) drifted.push(`${f} — missing from the copy`);
    else if (sha(vendored(join(SOURCE, f))) !== sha(readFileSync(mine))) drifted.push(`${f} — differs from the engine`);
  }
  const inline = join(VENDOR, "wasm/inline.ts");
  if (!existsSync(inline) || readFileSync(inline, "utf8") !== INLINE_STUB) drifted.push("wasm/inline.ts — not the generated stub");

  if (drifted.length > 0) {
    console.error("the vendored OpenSync client has drifted from the engine:\n");
    for (const d of drifted) console.error(`  ${d}`);
    console.error("\nrun `npm run vendor:opensync` and commit the result.");
    process.exit(1);
  }
  console.log(`vendored OpenSync client matches the engine (${FILES.length} files)`);
  process.exit(0);
}

rmSync(VENDOR, { recursive: true, force: true });
mkdirSync(join(VENDOR, "wasm"), { recursive: true });

const files = {};
for (const f of FILES) {
  const from = join(SOURCE, f);
  if (!existsSync(from)) {
    console.error(`the engine has no ${f} — has the client been rearranged?`);
    process.exit(1);
  }
  const bytes = vendored(from);
  writeFileSync(join(VENDOR, f), bytes);
  files[f] = sha(bytes);
}
writeFileSync(join(VENDOR, "wasm/inline.ts"), INLINE_STUB);

writeFileSync(
  STAMP,
  `${JSON.stringify(
    {
      note: "Generated by scripts/vendor-opensync.mjs. Do not edit anything in this directory.",
      source: "opensync — packages/client/src",
      vendored: new Date().toISOString().slice(0, 10),
      files,
    },
    null,
    2,
  )}\n`,
);

writeFileSync(
  join(VENDOR, "README.md"),
  `# Vendored: the OpenSync browser client

**Generated. Do not edit anything in this directory.**

Copied from the engine's \`packages/client/src\` by
\`scripts/vendor-opensync.mjs\`, so that this repository builds on its own: a
CI runner clones one repository and has no engine beside it. The only change
is a \`@ts-nocheck\` line atop each \`.ts\` file; the script says why.

\`wasm/opensync_wasm_bg.wasm\` is the compiled Rust core, built from the
\`opensync-*\` crates in the engine repository. \`wasm/inline.ts\` is an empty
stub, not the engine's base64 copy: the extension loads the binary instead.

The client is MIT-licensed by the OpenSync contributors, the same copy
opensync-obsidian vendors.

To refresh, with the engine checked out beside this repository:

    npm run vendor:opensync        # copy again
    npm run vendor:opensync:check  # fail if the copy has drifted

The check runs in \`npm test\`. Where the engine is absent it passes quietly.
`,
);

console.log(`vendored ${FILES.length} files + inline stub → ${relative(EXT, VENDOR)}`);
